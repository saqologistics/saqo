-- Keep operational data private. The server will connect using a database role.
BEGIN;

CREATE SCHEMA saqo;
REVOKE ALL ON SCHEMA saqo FROM PUBLIC, anon, authenticated;

CREATE TABLE saqo.profiles (
  id text PRIMARY KEY,
  email text UNIQUE NOT NULL,
  password_hash text NOT NULL,
  full_name text NOT NULL,
  phone text NOT NULL,
  role text NOT NULL CHECK (role IN ('client', 'rider', 'admin')),
  account_status text NOT NULL DEFAULT 'active' CHECK (account_status IN ('active', 'suspended')),
  created_at timestamptz NOT NULL
);

CREATE TABLE saqo.customers (
  id text PRIMARY KEY,
  profile_id text UNIQUE NOT NULL REFERENCES saqo.profiles(id) ON DELETE CASCADE,
  default_state text NOT NULL DEFAULT 'Katsina'
);

CREATE TABLE saqo.riders (
  id text PRIMARY KEY,
  profile_id text UNIQUE NOT NULL REFERENCES saqo.profiles(id) ON DELETE CASCADE,
  vehicle_type text NOT NULL,
  plate_number text NOT NULL,
  home_state text NOT NULL,
  verification_status text NOT NULL DEFAULT 'pending' CHECK (verification_status IN ('pending', 'verified', 'rejected')),
  is_online smallint NOT NULL DEFAULT 0 CHECK (is_online IN (0, 1)),
  current_lat double precision NOT NULL,
  current_lng double precision NOT NULL,
  last_location_at timestamptz NOT NULL,
  completed_deliveries_count integer NOT NULL DEFAULT 0,
  total_earnings_ngn numeric(14, 2) NOT NULL DEFAULT 0,
  rating double precision NOT NULL DEFAULT 5.0
);

CREATE TABLE saqo.rider_locations (
  id text PRIMARY KEY,
  rider_id text NOT NULL REFERENCES saqo.riders(id) ON DELETE CASCADE,
  lat double precision NOT NULL,
  lng double precision NOT NULL,
  recorded_at timestamptz NOT NULL
);

CREATE TABLE saqo.delivery_requests (
  id text PRIMARY KEY,
  queue_order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  tracking_code text UNIQUE NOT NULL,
  customer_id text NOT NULL REFERENCES saqo.customers(id) ON DELETE CASCADE,
  pickup_state text NOT NULL,
  pickup_address text NOT NULL,
  pickup_lat double precision NOT NULL,
  pickup_lng double precision NOT NULL,
  destination_state text NOT NULL,
  destination_address text NOT NULL,
  destination_lat double precision NOT NULL,
  destination_lng double precision NOT NULL,
  recipient_name text NOT NULL,
  recipient_phone text NOT NULL,
  service_tier text NOT NULL CHECK (service_tier IN ('local', 'inter_city', 'inter_state')),
  distance_km double precision NOT NULL,
  estimated_minutes integer NOT NULL,
  delivery_fee_ngn numeric(14, 2) NOT NULL,
  delivery_otp text NOT NULL,
  otp_verified smallint NOT NULL DEFAULT 0 CHECK (otp_verified IN (0, 1)),
  status text NOT NULL,
  assigned_rider_id text REFERENCES saqo.riders(id),
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  payment_method text NOT NULL DEFAULT 'cash',
  payment_status text NOT NULL DEFAULT 'pending',
  payment_reference text
);

CREATE TABLE saqo.parcels (
  id text PRIMARY KEY,
  delivery_id text UNIQUE NOT NULL REFERENCES saqo.delivery_requests(id) ON DELETE CASCADE,
  category text NOT NULL,
  description text NOT NULL,
  weight_kg double precision NOT NULL DEFAULT 1
);

CREATE TABLE saqo.delivery_assignments (
  id text PRIMARY KEY,
  delivery_id text NOT NULL REFERENCES saqo.delivery_requests(id) ON DELETE CASCADE,
  rider_id text NOT NULL REFERENCES saqo.riders(id) ON DELETE CASCADE,
  status text NOT NULL CHECK (status IN ('offered', 'accepted', 'rejected', 'timed_out', 'reassigned')),
  score double precision NOT NULL,
  distance_to_pickup_km double precision NOT NULL,
  route_compatibility_score double precision NOT NULL,
  offered_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  responded_at timestamptz
);

CREATE TABLE saqo.delivery_status_history (
  id text PRIMARY KEY,
  delivery_id text NOT NULL REFERENCES saqo.delivery_requests(id) ON DELETE CASCADE,
  status text NOT NULL,
  note text NOT NULL,
  actor_role text NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE saqo.delivery_otp_attempts (
  delivery_id text PRIMARY KEY REFERENCES saqo.delivery_requests(id) ON DELETE CASCADE,
  attempts integer NOT NULL,
  reset_at bigint NOT NULL
);

CREATE TABLE saqo.login_attempts (
  bucket text PRIMARY KEY,
  attempts integer NOT NULL,
  reset_at bigint NOT NULL
);

CREATE TABLE saqo.payments (
  id text PRIMARY KEY,
  delivery_id text UNIQUE NOT NULL REFERENCES saqo.delivery_requests(id) ON DELETE CASCADE,
  amount_ngn numeric(14, 2) NOT NULL,
  rider_payout_ngn numeric(14, 2) NOT NULL,
  platform_fee_ngn numeric(14, 2) NOT NULL,
  status text NOT NULL CHECK (status IN ('pending', 'settled', 'refunded')),
  created_at timestamptz NOT NULL
);

CREATE TABLE saqo.notifications (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES saqo.profiles(id) ON DELETE CASCADE,
  title text NOT NULL,
  message text NOT NULL,
  delivery_id text REFERENCES saqo.delivery_requests(id) ON DELETE SET NULL,
  is_read smallint NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
  created_at timestamptz NOT NULL
);

CREATE TABLE saqo.complaints (
  id text PRIMARY KEY,
  ticket_type text NOT NULL DEFAULT 'complaint' CHECK (ticket_type IN ('complaint', 'suggestion')),
  delivery_id text REFERENCES saqo.delivery_requests(id) ON DELETE SET NULL,
  reporter_id text NOT NULL REFERENCES saqo.profiles(id) ON DELETE CASCADE,
  subject text NOT NULL,
  details text NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'investigating', 'resolved')),
  resolution_note text,
  created_at timestamptz NOT NULL
);

CREATE TABLE saqo.platform_settings (
  id integer PRIMARY KEY CHECK (id = 1),
  max_active_parcels_per_rider integer NOT NULL CHECK (max_active_parcels_per_rider >= 1),
  search_radius_km double precision NOT NULL,
  offer_timeout_seconds integer NOT NULL,
  base_local_fee_ngn numeric(14, 2) NOT NULL,
  per_km_rate_ngn numeric(14, 2) NOT NULL,
  inter_state_surcharge_ngn numeric(14, 2) NOT NULL,
  rider_commission_percent double precision NOT NULL,
  whatsapp_support_number text NOT NULL,
  show_delivery_state_selectors smallint NOT NULL DEFAULT 0 CHECK (show_delivery_state_selectors IN (0, 1))
);

CREATE TABLE saqo.support_conversations (
  id text PRIMARY KEY,
  visitor_token text NOT NULL,
  user_id text REFERENCES saqo.profiles(id) ON DELETE SET NULL,
  visitor_name text NOT NULL,
  visitor_email text,
  visitor_phone text,
  tracking_code text,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'pending', 'resolved', 'closed')),
  assigned_admin_id text REFERENCES saqo.profiles(id) ON DELETE SET NULL,
  unread_by_admin integer NOT NULL DEFAULT 0,
  unread_by_visitor integer NOT NULL DEFAULT 0,
  last_message_preview text,
  last_message_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE saqo.support_messages (
  id text PRIMARY KEY,
  conversation_id text NOT NULL REFERENCES saqo.support_conversations(id) ON DELETE CASCADE,
  sender_role text NOT NULL CHECK (sender_role IN ('visitor', 'client', 'admin', 'system')),
  sender_name text NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE saqo.whatsapp_sessions (
  phone text PRIMARY KEY,
  draft jsonb,
  profile_id text REFERENCES saqo.profiles(id),
  support_conversation_id text REFERENCES saqo.support_conversations(id) ON DELETE SET NULL,
  last_inbound_at timestamptz NOT NULL
);

CREATE TABLE saqo.whatsapp_inbound_messages (
  message_sid text PRIMARY KEY,
  received_at timestamptz NOT NULL
);

CREATE INDEX ON saqo.rider_locations(rider_id, recorded_at DESC);
CREATE INDEX ON saqo.delivery_requests(customer_id, created_at DESC);
CREATE INDEX ON saqo.delivery_requests(assigned_rider_id, status);
CREATE INDEX ON saqo.delivery_requests(created_at, queue_order)
  WHERE status IN ('pending_dispatch', 'no_rider_available') AND (payment_method = 'cash' OR payment_status = 'paid');
CREATE INDEX ON saqo.delivery_assignments(delivery_id, rider_id);
CREATE INDEX ON saqo.delivery_assignments(rider_id, offered_at DESC);
CREATE INDEX ON saqo.delivery_assignments(expires_at) WHERE status = 'offered';
CREATE UNIQUE INDEX one_open_offer_per_delivery ON saqo.delivery_assignments(delivery_id) WHERE status = 'offered';
CREATE INDEX ON saqo.delivery_status_history(delivery_id, created_at);
CREATE INDEX ON saqo.login_attempts(reset_at);
CREATE INDEX ON saqo.notifications(user_id, created_at DESC);
CREATE INDEX ON saqo.support_conversations(visitor_token);
CREATE INDEX ON saqo.support_conversations(user_id);
CREATE INDEX ON saqo.support_messages(conversation_id, created_at);

