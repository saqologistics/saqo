  id, max_active_parcels_per_rider, search_radius_km, offer_timeout_seconds, base_local_fee_ngn,
  per_km_rate_ngn, inter_state_surcharge_ngn, rider_commission_percent, whatsapp_support_number
) VALUES (1, 3, 85, 45, 350, 22, 3500, 75, '2348007276000');

COMMIT;
