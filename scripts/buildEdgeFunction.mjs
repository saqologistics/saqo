import esbuild from 'esbuild';
import path from 'node:path';

const rewriteToDenoSpecifiers = {
  name: 'saqo-deno-externals',
  setup(build) {
    build.onResolve({ filter: /^(pg|@supabase\/supabase-js)$/ }, (args) => ({
      path: args.path === 'pg' ? 'npm:pg@8.23.1' : 'npm:@supabase/supabase-js@2',
      external: true,
    }));
    build.onResolve({ filter: /^(node:sqlite|ws|express|vite)$/ }, (args) => ({
      path: args.path,
      external: true,
    }));
  },
};

await esbuild.build({
  entryPoints: [path.resolve('supabase/functions/saqo-api/entry.ts')],
  outfile: path.resolve('supabase/functions/saqo-api/index.ts'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2022',
  external: ['node:*'],
  plugins: [rewriteToDenoSpecifiers],
  banner: {
    js: '// @ts-nocheck\n// Generated by scripts/buildEdgeFunction.mjs. Do not edit directly.\nimport "jsr:@supabase/functions-js/edge-runtime.d.ts";',
  },
});

console.log('Bundled supabase/functions/saqo-api/index.ts');
